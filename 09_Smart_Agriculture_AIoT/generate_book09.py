def clean_latex(text):
    text = text.replace(r'\\%', '%').replace(r'\%', '%')
    text = text.replace(r'\\_', '_').replace(r'\_', '_')
    text = text.replace(r'\\#', '#').replace(r'\#', '#')
    text = text.replace(r'\\&', '&').replace(r'\&', '&')

    parts = text.split('$')
    new_parts = []
    for idx, p in enumerate(parts):
        if idx % 2 == 1:
            p_math = p.replace('%', r'\%')
            new_parts.append('$' + p_math + '$')
        else:
            p_text = p
            p_text = p_text.replace('&', r'\&')
            p_text = p_text.replace('%', r'\%')
            p_text = p_text.replace('#', r'\#')
            p_text = p_text.replace('_', r'\_')
            new_parts.append(p_text)
    text = ''.join(new_parts)

    text = text.replace('°C', '$^{\\circ}$C')
    text = text.replace('°', '$^{\\circ}$')
    text = text.replace('→', '$\\rightarrow$')
    text = text.replace('←', '$\\leftarrow$')
    text = text.replace('±', '$\\pm$')
    text = text.replace('μ', '$\\mu$')
    text = text.replace('µ', '$\\mu$')
    text = text.replace('×', '$\\times$')
    text = text.replace('≤', '$\\le$')
    text = text.replace('≥', '$\\ge$')
    text = text.replace('~', '$\\sim$')
    text = re.sub(r'ได้แก่\s*[:：]', 'ได้แก่ ', text)
    text = re.sub(r'ดังนี้\s*[:：]', 'ดังนี้ ', text)
    text = re.sub(r'วัตถุประสงค์\s*[:：]', 'วัตถุประสงค์ ', text)
    text = re.sub(r'เนื้อหา\s*[:：]', 'เนื้อหา ', text)
    text = re.sub(r'ขั้นตอน\s*[:：]', 'ขั้นตอน ', text)
    return text

def clean_heading_text(h):
    h = re.sub(r'\\textit\{([^}]+)\}', r'\1', h)
    h = re.sub(r'textit([A-Za-z]+)', r'\1', h)
    h = h.replace('\\', '')
    h = re.sub(r'[^\w\s\(\)\-\.\,\u0E00-\u0E7F]', '', h)
    h = h.replace(':', '').replace('：', '').strip()
    h = re.sub(r'^[0-9]+(\.[0-9]+)*\s*', '', h)
    h = re.sub(r'\s*\([a-zA-Z\s\-\,\.\/0-9]+\)', '', h).strip()
    return clean_latex(h)

