def clean_latex(text):
    text = text.replace(r'\\%', '%').replace(r'\%', '%')
    text = text.replace(r'\\_', '_').replace(r'\_', '_')
    text = text.replace(r'\\#', '#').replace(r'\#', '#')
    text = text.replace(r'\\&', '&').replace(r'\&', '&')

    # Split by math delimiter $ to protect math
    parts = text.split('$')
    new_parts = []
    for idx, p in enumerate(parts):
        if idx % 2 == 1:
            # Inside math mode: do NOT escape _
            p_math = p.replace('%', r'\%')
            new_parts.append('$' + p_math + '$')
        else:
            # Outside math mode
            p_text = p
            p_text = p_text.replace('&', r'\&')
            p_text = p_text.replace('%', r'\%')
            p_text = p_text.replace('#', r'\#')
            p_text = p_text.replace('_', r'\_')
            new_parts.append(p_text)
    text = ''.join(new_parts)

    text = text.replace('°C', '$^{\\circ}$C')
    text = text.replace('°', '$^{\\circ}$')
    text = text.replace('→', '$\\rightarrow$')
    text = text.replace('←', '$\\leftarrow$')
    text = text.replace('±', '$\\pm$')
    text = text.replace('μ', '$\\mu$')
    text = text.replace('µ', '$\\mu$')
    text = text.replace('×', '$\\times$')
    text = text.replace('≤', '$\\le$')
    text = text.replace('≥', '$\\ge$')
    text = text.replace('~', '$\\sim$')
    text = re.sub(r'ได้แก่\s*[:：]', 'ได้แก่ ', text)
    text = re.sub(r'ดังนี้\s*[:：]', 'ดังนี้ ', text)
    text = re.sub(r'วัตถุประสงค์\s*[:：]', 'วัตถุประสงค์ ', text)
    text = re.sub(r'เนื้อหา\s*[:：]', 'เนื้อหา ', text)
    text = re.sub(r'ขั้นตอน\s*[:：]', 'ขั้นตอน ', text)
    return text


def clean_heading_text(h):
    h = re.sub(r'\\textit\{([^}]+)\}', r'\1', h)
    h = re.sub(r'textit([A-Za-z]+)', r'\1', h)
    h = h.replace('\\', '')
    h = re.sub(r'[^\w\s\(\)\-\.\,\u0E00-\u0E7F]', '', h)
    h = h.replace(':', '').replace('：', '').strip()
    h = re.sub(r'^[0-9]+(\.[0-9]+)*\s*', '', h)
    h = re.sub(r'\s*\([a-zA-Z\s\-\,\.\/0-9]+\)', '', h).strip()
    return clean_latex(h)

def parse_syllabus(filepath, chap_num):
    if not os.path.exists(filepath):
        return ""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    out = []
    out.append(f"\\section*{{แผนบริหารการสอนประจำบทที่ {chap_num}}}")
    out.append(f"\\addcontentsline{{toc}}{{section}}{{แผนบริหารการสอนประจำบทที่ {chap_num}}}\n")

    parts = re.split(r'###\s+', content)
    for p in parts[1:]:
        p_lines = p.strip().split('\n')
        title_line = p_lines[0].strip()
        body_lines = p_lines[1:]

        clean_title = clean_heading_text(title_line)
        if "ข้อมูลทั่วไป" in clean_title:
            continue
        
        out.append(f"\\noindent\\textbf{{{clean_title}}}\n")
        
        if any('|' in l for l in body_lines):
            table_lines = [l for l in body_lines if '|' in l]
            rows = []
            for tl in table_lines:
                if re.match(r'^\s*\|?\s*:?-+:?\s*\|', tl):
                    continue
                cells = [clean_latex(c.strip().replace('**', '')) for c in tl.strip().strip('|').split('|')]
                if cells and any(cells):
                    rows.append(cells)
            if rows:
                num_cols = max(len(r) for r in rows)
                col_def = "p{0.5\\textwidth} p{0.3\\textwidth} c" if num_cols == 3 else "X " * num_cols
                out.append("\\begin{table}[H]")
                out.append("\\centering\\small")
                out.append(f"\\begin{{tabularx}}{{\\textwidth}}{{{col_def}}}")
                out.append("\\toprule")
                out.append(" & ".join([f"\\textbf{{{c}}}" for c in rows[0]]) + " \\\\")
                out.append("\\midrule")
                for r in rows[1:]:
                    while len(r) < num_cols:
                        r.append("")
                    out.append(" & ".join(r) + " \\\\")
                out.append("\\bottomrule")
                out.append("\\end{tabularx}")
                out.append("\\end{table}\n")
        else:
            items = []
            for bl in body_lines:
                bl_str = bl.strip()
                if not bl_str or bl_str.startswith('---'):
                    continue
                item_match = re.match(r'^(\*|-|\d+\.)\s+(.+)$', bl_str)
                if item_match:
                    item_text = item_match.group(2).replace('**', '')
                    items.append(clean_latex(item_text))
                else:
                    items.append(clean_latex(bl_str.replace('**', '')))
            
            if items:
                out.append("\\begin{enumerate}")
                for itm in items:
                    out.append(f"    \\item {itm}")
                out.append("\\end{enumerate}\n")

    out.append("\\newpage\n")
    return "\n".join(out)

